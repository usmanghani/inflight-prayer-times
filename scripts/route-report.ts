/**
 * Route report: run every library flight (both directions) through the in-flight engine on one date.
 *
 *   npx vite-node scripts/route-report.ts [YYYY-MM-DD]      (default 2026-10-12)
 *
 * Prints a table to the console and writes docs/route-report.md.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveAirport } from '../src/data/airports';
import { FLIGHT_LIBRARY, libraryFlightToLeg } from '../src/data/flights';
import { buildJourney } from '../src/flight/journey';
import { PRAYER_LABEL, computeInflight } from '../src/prayer/inflight';
import { DEFAULT_SETTINGS } from '../src/prayer/methods';

const date = process.argv[2] ?? '2026-10-12';
if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) {
  console.error(`Invalid date "${date}" (expected YYYY-MM-DD)`);
  process.exit(1);
}

const hm = (min: number): string => `${Math.floor(min / 60)}h${String(Math.round(min % 60)).padStart(2, '0')}`;
const lat = (x: number): string => `${Math.abs(x).toFixed(1)}°${x >= 0 ? 'N' : 'S'}`;
const SHORT: Record<string, string> = {
  windowRepeated: 'repeated', windowSkipped: 'skipped', highLatitudeRuleUsed: 'high-lat rule', polarDay: 'polar day', polarNight: 'polar night',
};

interface Row {
  flight: string; route: string; block: string; airCount: number; prayers: string; anomalies: string; maxLat: string; error?: string;
}

const rows: Row[] = [];
const totals = { flights: 0, failed: 0, withInAir: 0, repeated: 0, skipped: 0, polar: 0, highLat: 0, ms: 0 };
const t0 = performance.now();

for (const fl of FLIGHT_LIBRARY) {
  try {
    const leg = libraryFlightToLeg(fl, date, resolveAirport);
    const journey = buildJourney([leg], resolveAirport);
    const r = computeInflight(journey, DEFAULT_SETTINGS, { stepMinutes: 1, tzUnderAircraft: false });
    const air = r.events.filter((e) => !e.state.onGround);
    const counts: Record<string, number> = {};
    for (const a of r.anomalies) counts[a.kind] = (counts[a.kind] ?? 0) + 1;
    let maxLat = 0;
    for (const s of r.samples) if (Math.abs(s.state.lat) > Math.abs(maxLat)) maxLat = s.state.lat;
    rows.push({
      flight: fl.flightNumber,
      route: `${fl.from}→${fl.to}`,
      block: hm((leg.arrivalUtc.getTime() - leg.departureUtc.getTime()) / 60000),
      airCount: air.length,
      prayers: air.map((e) => PRAYER_LABEL[e.prayer]).join(', ') || '–',
      anomalies: Object.entries(counts).map(([k, n]) => `${n}× ${SHORT[k] ?? k}`).join(', ') || '–',
      maxLat: lat(maxLat),
    });
    totals.flights++;
    if (air.length > 0) totals.withInAir++;
    totals.repeated += counts.windowRepeated ?? 0;
    totals.skipped += counts.windowSkipped ?? 0;
    totals.polar += (counts.polarDay ?? 0) + (counts.polarNight ?? 0);
    totals.highLat += counts.highLatitudeRuleUsed ?? 0;
  } catch (err) {
    totals.failed++;
    rows.push({ flight: fl.flightNumber, route: `${fl.from}→${fl.to}`, block: '–', airCount: 0, prayers: '–', anomalies: '–', maxLat: '–', error: (err as Error).message });
  }
}
totals.ms = performance.now() - t0;

const header = ['Flight', 'Route', 'Block', 'Windows opened in air', 'Prayers (in order)', 'Anomalies', 'Max latitude'];
const line = (r: Row): string[] => [r.flight, r.route, r.block, String(r.airCount), r.error ? `ERROR: ${r.error}` : r.prayers, r.anomalies, r.maxLat];

// console table
const widths = header.map((h, i) => Math.max(h.length, ...rows.map((r) => line(r)[i].length)));
const fmt = (cells: string[]): string => cells.map((c, i) => c.padEnd(widths[i])).join('  ');
console.log(`In-flight prayer windows, ${FLIGHT_LIBRARY.length} library flights, departing ${date} (DEFAULT_SETTINGS: Hanafi, Karachi 18°/18°, angle-based)\n`);
console.log(fmt(header));
console.log(widths.map((w) => '-'.repeat(w)).join('  '));
for (const r of rows) console.log(fmt(line(r)));
console.log(
  `\n${totals.flights} flights computed (${totals.failed} failed) in ${(totals.ms / 1000).toFixed(1)} s; ` +
  `${totals.withInAir} open at least one window in the air; ` +
  `anomalies: ${totals.repeated} repeated, ${totals.skipped} skipped, ${totals.polar} polar, ${totals.highLat} high-latitude-rule.`,
);

// markdown
const md = [
  `# Route report: ${date}`,
  '',
  `Generated by \`npx vite-node scripts/route-report.ts ${date}\`. Settings: Hanafi Asr, Karachi 18°/18°, angle-based high-latitude rule, horizon dip on for sunrise/sunset. ` +
  'Schedules in the flight library are representative, not live timetables.',
  '',
  `* ${totals.flights} flights computed${totals.failed ? `, ${totals.failed} failed` : ''}; ${totals.withInAir} open at least one prayer window in the air.`,
  `* Anomalies over all flights: ${totals.repeated} repeated windows, ${totals.skipped} skipped windows, ${totals.polar} polar day/night stretches, ${totals.highLat} high-latitude-rule times.`,
  '',
  `| ${header.join(' | ')} |`,
  `| ${header.map(() => '---').join(' | ')} |`,
  ...rows.map((r) => `| ${line(r).join(' | ')} |`),
  '',
].join('\n');
const out = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'route-report.md');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, md);
console.log(`\nWrote ${out}`);
